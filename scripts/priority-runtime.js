module.exports = function addPriorityRuntime(html) {
  const script = [
    '<script id="wct-priority-runtime">',
    '(function(){',
    '  function choosePriority(button){',
    '    if(!button || button.disabled) return false;',
    '    var form = button.closest("form");',
    '    if(!form) return false;',
    '    var field = form.querySelector("input[name=priority]");',
    '    if(!field) return false;',
    '    var value = String(button.getAttribute("data-value") || button.textContent || "").trim();',
    '    if(["High","Medium","Low"].indexOf(value) === -1) return false;',
    '    field.value = value;',
    '    var group = button.closest(".wct-priority-buttons");',
    '    if(!group) return false;',
    '    group.querySelectorAll(".wct-priority-choice").forEach(function(item){',
    '      var selected = item === button;',
    '      item.classList.toggle("is-selected", selected);',
    '      item.setAttribute("aria-pressed", selected ? "true" : "false");',
    '      item.setAttribute("data-selected", selected ? "true" : "false");',
    '    });',
    '    field.dispatchEvent(new Event("change", {bubbles:true}));',
    '    return true;',
    '  }',
    '  function findButton(event){',
    '    var target = event.target;',
    '    return target && target.closest ? target.closest("button.wct-priority-choice") : null;',
    '  }',
    '  document.addEventListener("pointerdown", function(event){',
    '    var button = findButton(event); if(button) choosePriority(button);',
    '  }, true);',
    '  document.addEventListener("click", function(event){',
    '    var button = findButton(event); if(!button) return;',
    '    event.preventDefault(); choosePriority(button);',
    '  }, true);',
    '  document.addEventListener("keydown", function(event){',
    '    if(event.key !== "Enter" && event.key !== " ") return;',
    '    var button = findButton(event); if(button){ event.preventDefault(); choosePriority(button); }',
    '  }, true);',
    '  window.wctPriorityRuntimeReady = true;',
    '})();',
    '</script>'
  ].join("\n");
  return html.replace("</body>", script + "\n</body>");
};